/** ধারার `content` পার্সার (গেজেট v2) — অর্ডার-সংরক্ষী ব্লক-স্ট্রিম।
 *  • (ক)(খ)(১)(২)… প্রিফিক্স → item (উপধারা-চিপ)
 *  • "০১."/"৩." সংখ্যা-প্রিফিক্স → enum (পদবিন্যাস/গণনা-তালিকা)
 *  • বাকি সব → lead প্যারাগ্রাফ
 *  groups = রেন্ডার-ক্রমে গুচ্ছ ({type:'lead'|'enum'|'items'}) — ধারাবাহিক item-গুলো একটি
 *  <ol>-এ গ্রুপ হয়; ব্যাকওয়ার্ড-কম্প্যাট: lead[]/items[] অপরিবর্তিত আকারে থাকে। */
function parseSectionContent(content) {
  const out = { blocks: [], groups: [], lead: [], items: [] };
  if (!content) return out;
  const paras = String(content)
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  const ITEM = /^\(([\u0980-\u09FF]{1,3})\)\s*/;
  const ENUM = /^([০-৯]{1,2})\.\s*/;
  for (const p of paras) {
    const m = p.match(ITEM);
    if (m) {
      const it = { type: 'item', marker: m[1], text: p.slice(m[0].length) };
      out.blocks.push(it);
      out.items.push(it);
      continue;
    }
    const e = p.match(ENUM);
    if (e) {
      // দফা-শিরোনাম: "০১. সাংগঠনিক বছর পুনর্নির্ধারণ: বাংলাদেশ…" → { title: '…', text: '…' }
      let rest = p.slice(e[0].length);
      let title = '';
      const ci = rest.indexOf(':');
      if (ci > 0 && ci <= 90 && !/[।!?]/.test(rest.slice(0, ci))) {
        title = rest.slice(0, ci).trim();
        rest = rest.slice(ci + 1).trim();
      }
      out.blocks.push({ type: 'enum', no: e[1], title, text: rest });
      continue;
    }
    out.blocks.push({ type: 'lead', text: p });
    out.lead.push(p);
  }
  // রেন্ডার-গুচ্ছ: ধারাবাহিক item → এক 'items'-গ্রুপ; lead/enum → একক-গ্রুপ
  let buf = null;
  const flush = () => {
    if (buf && buf.length) out.groups.push({ type: 'items', items: buf });
    buf = null;
  };
  for (const b of out.blocks) {
    if (b.type === 'item') {
      if (!buf) buf = [];
      buf.push(b);
    } else {
      flush();
      out.groups.push(b);
    }
  }
  flush();
  return out;
}

/** "ধারা-৪১ : আয়ের উৎস" → { badge: 'ধারা-৪১', title: 'আয়ের উৎস' } */
function splitSectionTitle(title) {
  const t = String(title || '').trim();
  const parts = t.split(/\s*[:：]\s*/);
  if (parts.length >= 2) return { badge: parts[0], title: parts.slice(1).join(' : ') };
  return { badge: '', title: t };
}

/** আরবি সংখ্যা → বাংলা সংখ্যা (১২ → ১২) */
function toBn(n) {
  return String(n).replace(/[0-9]/g, (d) => '০১২৩৪৫৬৭৮৯'[d]);
}


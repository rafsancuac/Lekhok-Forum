/* ── ১. ন্যূনতম বৈধ PDF (ASCII-টেক্সট, xref-সহ — যেকোনো ভিউয়ারে খোলে) ── */
function makePdf(lines) {
  const objs = [];
  objs[1] = '<</Type/Catalog/Pages 2 0 R>>';
  objs[2] = '<</Type/Pages/Kids[3 0 R]/Count 1>>';
  objs[3] = '<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]/Contents 4 0 R/Resources<</Font<</F1 5 0 R>>>>>>';
  let stream = 'BT /F1 20 Tf 60 720 Td ';
  lines.forEach((l, i) => { stream += `(${l}) Tj 0 -28 Td `; });
  stream += 'ET';
  objs[4] = '<</Length ' + stream.length + '>>stream\n' + stream + '\nendstream';
  objs[5] = '<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>';
  let out = '%PDF-1.4\n';
  const offs = [];
  for (let i = 1; i <= 5; i++) { offs[i] = out.length; out += i + ' 0 obj' + objs[i] + 'endobj\n'; }
  const xref = out.length;
  out += 'xref\n0 6\n0000000000 65535 f \n';
  for (let i = 1; i <= 5; i++) out += String(offs[i]).padStart(10, '0') + ' 00000 n \n';
  out += 'trailer<</Size 6/Root 1 0 R>>\nstartxref\n' + xref + '\n%%EOF';
  return Buffer.from(out, 'latin1');
}

/* ── ২. আসল PCM WAV (৪৪০Hz সাইন — ব্রাউজারে প্লে হয়) ── */
function makeWav(seconds, freq) {
  const rate = 8000, n = rate * seconds;
  const data = Buffer.alloc(44 + n * 2);
  data.write('RIFF', 0); data.writeUInt32LE(36 + n * 2, 4); data.write('WAVE', 8);
  data.write('fmt ', 12); data.writeUInt32LE(16, 16); data.writeUInt16LE(1, 20);
  data.writeUInt16LE(1, 22); data.writeUInt32LE(rate, 24); data.writeUInt32LE(rate * 2, 28);
  data.writeUInt16LE(2, 32); data.writeUInt16LE(16, 34);
  data.write('data', 36); data.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) {
    const fade = Math.min(1, (seconds * rate - i) / 2000, i / 500 + 0.05);
    const v = Math.round(Math.sin(2 * Math.PI * freq * i / rate) * 11000 * fade);
    data.writeInt16LE(v, 44 + i * 2);
  }
  return data;
}

/* ── ৩. PNG (zlib + ম্যানুয়াল chunk — কোনো-নির্ভরতা নেই) ── */
function crc32(buf) {
  let c, crc = 0xFFFFFFFF;
  for (let i = 0; i < buf.length; i++) {
    c = (crc ^ buf[i]) & 0xFF;
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xFFFFFFFF) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32LE(data.length, 0); // পরে BE করব
  const t = Buffer.from(type, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32LE(crc32(Buffer.concat([t, data])), 0);
  const lenBE = Buffer.alloc(4); lenBE.writeUInt32BE(data.length, 0);
  const crcBE = Buffer.alloc(4); crcBE.writeUInt32BE(crc.readUInt32LE(0), 0);
  return Buffer.concat([lenBE, t, data, crcBE]);
}
function makePng(w, h, painter) {
  const raw = Buffer.alloc(h * (1 + w * 3));
  for (let y = 0; y < h; y++) {
    const rowStart = y * (1 + w * 3);
    raw[rowStart] = 0; // filter none
    for (let x = 0; x < w; x++) {
      const [r, g, b] = painter(x, y);
      const o = rowStart + 1 + x * 3;
      raw[o] = r; raw[o + 1] = g; raw[o + 2] = b;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8-bit RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0))
  ]);
}

